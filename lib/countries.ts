export const COUNTRIES: Country[] = ROWS.map(([code, name, aliases]) => ({
  code,
  name,
  aliases: [...aliases],
}));

const SEARCH_ENTRIES: readonly CatalogEntry[] = COUNTRIES.map((country) => ({
  id: country.code,
  name: country.name,
  category: 'Negara',
  aliases: country.aliases,
}));

const COUNTRY_INDEX = new Map<string, Country>();
for (const country of COUNTRIES) {
  for (const candidate of [country.code, country.name, ...country.aliases]) {
    const key = normalizeCatalogText(candidate);
    if (!key) continue;
    const previous = COUNTRY_INDEX.get(key);
    if (previous && previous.code !== country.code) {
      throw new Error(`Alias negara bentrok: ${candidate} (${previous.code} / ${country.code})`);
    }
    COUNTRY_INDEX.set(key, country);
  }
  COUNTRY_INDEX.set(catalogId(country.code), country);
}

export function findCountry(codeOrName: string): Country | null {
  return COUNTRY_INDEX.get(normalizeCatalogText(codeOrName)) ?? null;
}

export function searchCountries(query: string, limit = 8): Array<{ code: string; name: string }> {
  return searchCatalog(SEARCH_ENTRIES, query, limit).map(({ id, name }) => ({ code: id, name }));
}

export function isValidCountryCode(code: unknown): code is string {
  return typeof code === 'string' && /^[A-Z]{2}$/.test(code) && COUNTRIES.some((c) => c.code === code);
}
