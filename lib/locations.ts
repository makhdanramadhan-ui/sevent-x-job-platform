function toEntry([name, type, province, country, aliases]: LocationRow): LocationEntry {
  return {
    id: catalogId(name),
    name,
    type,
    province,
    country,
    category: type === 'special' ? 'Khusus' : province,
    aliases,
  };
}

const COUNTRY_LOCATION_ENTRIES: LocationEntry[] = COUNTRIES.map((country) => ({
  id: `country-${country.code.toLowerCase()}`,
  name: country.name,
  type: 'country',
  province: country.name,
  country: country.code,
  category: country.name,
  aliases: country.aliases,
}));

export const LOCATIONS: readonly LocationEntry[] = [
  ...INDONESIA_ROWS.map(toEntry),
  ...FOREIGN_CITY_ROWS.map(toEntry),
  ...COUNTRY_LOCATION_ENTRIES,
];

export const LOCATION_CANONICAL: ReadonlyMap<string, string> = buildCanonicalIndex(LOCATIONS);

const LOCATION_INDEX = new Map<string, LocationEntry>();
for (const location of LOCATIONS) {
  for (const candidate of [location.name, ...location.aliases]) {
    const key = normalizeCatalogText(candidate);
    if (!key) continue;
    const previous = LOCATION_INDEX.get(key);
    if (previous && previous.id !== location.id) {
      throw new Error(`Alias lokasi bentrok: ${candidate} (${previous.name} / ${location.name})`);
    }
    LOCATION_INDEX.set(key, location);
  }
}

export function findLocation(nameOrAlias: string): LocationEntry | null {
  return LOCATION_INDEX.get(normalizeCatalogText(nameOrAlias)) ?? null;
}

export function locationsForCountry(code: string): readonly LocationEntry[] {
  return LOCATIONS.filter((location) => location.country === code || location.country === '*');
}

export function searchLocations(query: string, country?: string): LocationEntry[] {
  const entries = country ? locationsForCountry(country) : LOCATIONS;
  const byId = new Map(entries.map((entry) => [entry.id, entry]));
  return searchCatalog(entries, query, 8)
    .map(({ id }) => byId.get(id))
    .filter((entry): entry is LocationEntry => entry !== undefined);
}
