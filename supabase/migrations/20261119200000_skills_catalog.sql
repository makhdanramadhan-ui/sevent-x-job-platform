do $$
begin
  create extension if not exists pg_trgm;
exception when others then
  raise notice 'pg_trgm tidak tersedia; memakai indeks btree lower(name)/slug sebagai fallback';
end;
$$;

create table if not exists public.skills (
  id bigint generated always as identity primary key,
  name text not null,
  slug text not null unique,
  category text not null,
  aliases text[] not null default '{}',
  constraint skills_name_length check (char_length(name) between 1 and 120),
  constraint skills_slug_length check (char_length(slug) between 1 and 120),
  constraint skills_category_length check (char_length(category) between 1 and 80),
  constraint skills_aliases_count check (coalesce(array_length(aliases, 1), 0) <= 20)
);

create index if not exists skills_lower_name_idx on public.skills (lower(name));
create index if not exists skills_slug_idx on public.skills (slug);
do $$
begin
  create index if not exists skills_name_trgm_idx on public.skills using gin (lower(name) gin_trgm_ops);
exception when others then
  raise notice 'indeks trgm tidak dibuat; pencarian memakai prefiks ilike';
end;
$$;
create index if not exists skills_aliases_gin_idx on public.skills using gin (aliases);

alter table public.skills enable row level security;

drop policy if exists skills_select_public on public.skills;
create policy skills_select_public on public.skills
  for select to anon, authenticated
  using (true);

revoke all on table public.skills from public, anon, authenticated;
grant select on table public.skills to anon, authenticated;
grant all on table public.skills to service_role;
grant usage, select on sequence public.skills_id_seq to service_role;

